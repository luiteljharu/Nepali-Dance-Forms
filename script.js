const danceGrid =
  document.getElementById(
    "danceGrid"
  );


const modal =
  document.getElementById(
    "danceModal"
  );


const modalContent =
  document.getElementById(
    "modalContent"
  );



function renderDances(
  filter = "all"
) {

  const filteredDances =
    dances.filter(

      dance =>
        filter === "all" ||
        dance.category === filter

    );


  danceGrid.innerHTML =
    filteredDances
      .map(

        (dance, index) => `

          <article
            class="dance-card"
            data-name="${dance.name}"
          >

            <div class="card-top">

              <span class="card-tag">
                ${dance.tag}
              </span>

              <span class="card-number">
                ${String(index + 1)
                  .padStart(2, "0")}
              </span>

            </div>


            <div class="card-art">
              ${dance.art}
            </div>


            <div>

              <h3>

                ${dance.name}

                <span
                  style="
                    font-family:
                    'Noto Sans Devanagari';

                    font-size:
                    0.48em;
                  "
                >

                  ${dance.nepali}

                </span>

              </h3>


              <p>
                ${dance.short}
              </p>

            </div>


            <span class="card-arrow">
              ↗
            </span>

          </article>

        `

      )
      .join("");

}



function openDance(
  danceName
) {

  const dance =
    dances.find(

      item =>
        item.name === danceName

    );


  if (!dance) {
    return;
  }


  modalContent.innerHTML = `

    <div class="modal-inner">

      <div class="modal-kicker">
        ${dance.tag}
      </div>


      <h3>

        ${dance.name}

        <span
          style="
            font-family:
            'Noto Sans Devanagari';

            font-size:
            0.45em;
          "
        >

          ${dance.nepali}

        </span>

      </h3>


      <span class="origin">
        ${dance.origin}
      </span>


      <p>
        ${dance.history}
      </p>

    </div>

  `;


  modal.showModal();

}



danceGrid.addEventListener(

  "click",

  event => {

    const card =
      event.target.closest(
        ".dance-card"
      );


    if (card) {

      openDance(
        card.dataset.name
      );

    }

  }

);



document
  .querySelector(
    ".modal-close"
  )
  .addEventListener(

    "click",

    () => {

      modal.close();

    }

  );



document
  .querySelectorAll(
    ".filter"
  )
  .forEach(

    button => {

      button.addEventListener(

        "click",

        () => {

          document
            .querySelectorAll(
              ".filter"
            )
            .forEach(

              item =>
                item.classList.remove(
                  "active"
                )

            );


          button.classList.add(
            "active"
          );


          renderDances(
            button.dataset.filter
          );

        }

      );

    }

  );



const menuButton =
  document.querySelector(
    ".menu-btn"
  );


const navigation =
  document.querySelector(
    ".nav-links"
  );



menuButton.addEventListener(

  "click",

  () => {

    navigation.classList.toggle(
      "open"
    );

  }

);



